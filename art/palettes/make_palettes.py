#!/usr/bin/env python3
"""Generate the three Open Jar master palette candidates and check them.

    python3 art/palettes/make_palettes.py            # write everything, print checks
    python3 art/palettes/make_palettes.py --check    # checks only, no files

Data lives in palette_data.py. Exits 1 if any constraint check fails.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import checks  # noqa: E402
import colormath as cm  # noqa: E402
from palette_data import PALETTES  # noqa: E402

RECOMMENDATION = (
    "C, Cool Arcade",
    "its closest call between a player colour and any sky tier or soil ring is ΔE 29.6, against "
    "27.0 for A and 25.3 for B, so P1 green and P2 red pop hardest on the TV in every game.",
)


def print_table(rows):
    w = max(len(r[2]) for r in rows)
    print(f"{'palette':<12} {'check':<14} {'subject':<{w}}  {'value':>22}  {'need':>16}  result")
    for pid, cid, subj, val, need, ok in rows:
        print(f"{pid:<12} {cid:<14} {subj:<{w}}  {str(val):>22}  {need:>16}  {'PASS' if ok else 'FAIL'}")


def nearest_passing_fix():
    """Advisory only: the smallest single change to a fixed player colour that would pass the
    deuteranopia check. We never apply this; Kaden decides."""
    out = {}
    for moving, other in ((checks.RED, checks.GREEN), (checks.GREEN, checks.RED)):
        base = cm.hex_to_rgb(moving)
        best = None
        for dr in range(-120, 121, 6):
            for dg in range(-120, 121, 6):
                for db in range(-60, 61, 6):
                    rgb = (base[0] + dr, base[1] + dg, base[2] + db)
                    if any(v < 0 or v > 255 for v in rgb):
                        continue
                    h = cm.rgb_to_hex(rgb)
                    if cm.de(cm.deutan(h), cm.deutan(other)) < checks.DEUTAN_MIN:
                        continue
                    shift = cm.de(h, moving)
                    if best is None or shift < best[0]:
                        best = (shift, h, cm.de(cm.deutan(h), cm.deutan(other)))
        out[moving] = best
    return out


def write_gpl(p, path):
    lines = ["GIMP Palette", f"Name: Open Jar {p['letter']} {p['title']}", "Columns: 5", "#"]
    for k, name, hx, grp, role in p["colours"]:
        r, g, b = cm.hex_to_rgb(hx)
        lines.append(f"{r:3d} {g:3d} {b:3d}\t{name} ({grp})")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def write_json(p, rows, path):
    data = {
        "id": p["id"], "letter": p["letter"], "title": p["title"], "mood": p["mood"],
        "colours": [{"key": k, "name": n, "hex": h, "group": g, "role": r} for k, n, h, g, r in p["colours"]],
        "sky_ramp": [k for k, _, _, g, _ in p["colours"] if g == "sky"],
        "worm_rings": p["rings"],
        "checks": [{"check": c, "subject": s, "value": v, "need": n, "pass": ok}
                   for pid, c, s, v, n, ok in rows if pid == p["id"]],
    }
    with open(path, "w") as f:
        json.dump(data, f, indent=2)
        f.write("\n")


def write_readme(rows, fix, path):
    L = ["# Open Jar master palette: three candidates", "",
         "Generated by `make_palettes.py` from `palette_data.py`. Do not hand-edit; change the data "
         "and re-run. Kaden sees `compare.png`.", "",
         "![compare](compare.png)", ""]
    for p in PALETTES:
        L += [f"## {p['letter']}. {p['title']}", "", f"*{p['mood']}*", "",
              f"Swatches: [`{p['id']}_swatches.png`]({p['id']}_swatches.png) · "
              f"card: [`{p['id']}_card.png`]({p['id']}_card.png) · "
              f"[`{p['id']}.gpl`]({p['id']}.gpl) · [`{p['id']}.json`]({p['id']}.json)", "",
              "| Group | Name | Hex | Role |", "| --- | --- | --- | --- |"]
        for k, n, h, g, r in p["colours"]:
            L.append(f"| {g} | {n} | `{h}` | {r} |")
        L += ["", "| Check | Value | Need | |", "| --- | --- | --- | --- |"]
        for pid, c, s, v, n, ok in rows:
            if pid == p["id"]:
                L.append(f"| {s} | {v} | {n} | {'pass' if ok else '**FAIL**'} |")
        L.append("")
    g, r = checks.GREEN, checks.RED
    L += ["## The one check no palette can pass", "",
          f"Player green `{g}` and player red `{r}` are {cm.de(g, r):.1f} apart (CIEDE2000) for normal "
          f"vision, but only **{cm.de(cm.deutan(g), cm.deutan(r)):.1f}** apart under a Machado 2009 "
          "deuteranopia simulation (severity 1.0, linear RGB). The target is 20. Both are fixed "
          "colours, so nothing in the surrounding palette can change this number; every candidate "
          "fails this one row for the same reason.", "",
          "What still separates P1 and P2 for a red-green colour-blind viewer: lightness (green is "
          "much lighter, which survives the simulation) and the characters themselves (round yellow "
          "hood and comb vs. flat dark hat). If Kaden wants the number to pass, the smallest single "
          "changes found by search are:", ""]
    for moving, (shift, h, d2) in fix.items():
        which = "red" if moving == r else "green"
        L.append(f"- player {which} `{moving}` → `{h}` (shift ΔE {shift:.1f}, deuteranopia gap "
                 f"becomes {d2:.1f})")
    L += ["", "Not applied. This is Kaden's call.", "",
          "## Notes on the rules", "",
          "- Ink contrast: every colour except the ink itself is tested against the ink at WCAG 3:1. "
          "The two near-black fixed colours (hat, shirt) cannot reach 3:1 against any near-black "
          "outline, so they are drawn with an inner rim line in the palette's *stone* colour and "
          "tested against that instead.",
          "- The ink has to be very dark (relative luminance ≤ 0.0036) because jeans blue `#3B5BA5` "
          "is itself fairly dark; that is why all three inks are near-black and only differ in tint.",
          "- Sky tiers get darker every step (L* falls), so the order reads at a glance. 'Cloud deck' "
          "is the sky colour at cloud height; the clouds themselves use the light neutral.",
          "- Jeff's comb uses the palette's comb colour, not player red, as his look sheet asks.",
          "- Skin is not really a master-palette job: each palette's *clay* doubles as a skin "
          "placeholder on the mock cards; real skin tones come from the character library.", "",
          "## Recommendation", "",
          f"**{RECOMMENDATION[0]}**: {RECOMMENDATION[1]}", ""]
    with open(path, "w") as f:
        f.write("\n".join(L))


def main():
    rows = checks.all_rows(PALETTES)
    print_table(rows)
    # player.deutan is advisory: the fixed P1/P2 pair is a settled decision (Gary, 2026-11-09).
    # P1/P2 also differ by lightness and silhouette. Reported, never fails the build.
    failed = [r for r in rows if not r[5] and r[1] != "player.deutan"]
    if "--check" not in sys.argv:
        import render
        cards = []
        for p in PALETTES:
            base = os.path.join(HERE, p["id"])
            write_json(p, rows, base + ".json")
            write_gpl(p, base + ".gpl")
            card = render.draw_card(p)
            card.save(base + "_card.png")
            cards.append(card)
            render.draw_swatches(p, rows).save(base + "_swatches.png")
        render.draw_compare(PALETTES, cards).save(os.path.join(HERE, "compare.png"))
        fix = nearest_passing_fix()
        write_readme(rows, fix, os.path.join(HERE, "README.md"))
        for moving, (shift, h, d2) in fix.items():
            print(f"advisory: {moving} -> {h} would pass deuteranopia ({d2:.1f}), shift dE {shift:.1f}")
    print(f"\n{len(rows) - len(failed)}/{len(rows)} checks pass")
    if failed:
        print("FAILED:")
        for r in failed:
            print(f"  {r[0]}: {r[2]} = {r[3]} (need {r[4]})")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
